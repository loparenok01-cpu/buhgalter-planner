-- Периодические пункты чек-листов (дополнение к FR-42).
--
-- Пункт чек-листа привязывается не только к конкретной дате, но и к периоду:
-- неделе, месяцу или кварталу. period_pos задаёт положение даты задачи
-- внутри периода: начало, середина или конец.
--
-- Пункт с конкретной датой: period = NULL, date заполнена.
-- Пункт с периодом:        period заполнена, date = NULL.
-- Пункт без привязки:      оба NULL — задача встаёт на начало периода применения.

ALTER TABLE checklist_items ADD COLUMN period     TEXT;
ALTER TABLE checklist_items ADD COLUMN period_pos TEXT;
